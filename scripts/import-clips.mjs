import { existsSync, mkdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repo = resolve(fileURLToPath(new URL("..", import.meta.url)));
const defaultSource = join(repo, "motions", "baselines.json");
const defaultOut = join(repo, "src", "generated", "motion-library.ts");

const args = process.argv.slice(2);
const outIdx = args.indexOf("--out");
const outArg = outIdx >= 0 ? args[outIdx + 1] : undefined;
const positional = args.filter((_, i) => i !== outIdx && i !== outIdx + 1);
const source = resolve(positional[0] ?? defaultSource);
const generatedPath = resolve(outArg ?? defaultOut);
const existingSeedPath = existsSync(generatedPath) ? generatedPath : defaultOut;

const defaultRig = {
  units: "normalized-height-100",
  height: 100,
  thigh: 22.5,
  shin: 22.5,
  foot: 7,
  torso: 30,
  neck: 4,
  headRadius: 11,
  upperArm: 17,
  forearm: 16
};

let existingLibrary = { version: 1, fps: 30, rig: defaultRig, clips: {} };
if (existsSync(existingSeedPath)) {
  const text = readFileSync(existingSeedPath, "utf8");
  const match = text.match(/GENERATED_MOTION_LIBRARY(?:: any)? = (.*);/s);
  if (match) {
    existingLibrary = JSON.parse(match[1]);
  }
}

const names = ["walk", "run", "jump", "stop", "point", "idle", "static-pose"];
const importedClips = {};
let importedRig = existingLibrary.rig ?? defaultRig;

if (statSync(source).isFile()) {
  const parsed = JSON.parse(readFileSync(source, "utf8"));
  if (parsed.rig) importedRig = parsed.rig;
  const sourceClips = parsed.clips ?? parsed;
  for (const name of names) {
    if (sourceClips[name]) importedClips[name] = sourceClips[name];
  }
} else {
  for (const name of names) {
    const clipFile = join(source, `${name}.json`);
    if (existsSync(clipFile)) {
      importedClips[name] = JSON.parse(readFileSync(clipFile, "utf8"));
    }
  }
}

const mergedClips = { ...(existingLibrary.clips ?? {}) };
for (const [id, clip] of Object.entries(importedClips)) {
  const prior = mergedClips[id];
  mergedClips[id] = prior?.meta && !clip.meta ? { ...clip, meta: prior.meta } : clip;
}

const sortedClips = Object.fromEntries(
  Object.entries(mergedClips).sort(([a], [b]) => a.localeCompare(b))
);

const library = {
  version: 1,
  fps: 30,
  rig: importedRig,
  clips: sortedClips
};

mkdirSync(dirname(generatedPath), { recursive: true });
writeFileSync(
  generatedPath,
  `/* eslint-disable */\n// Generated by scripts/motions/assemble.mjs. Do not edit by hand.\nexport const GENERATED_MOTION_LIBRARY: any = ${JSON.stringify(library).replaceAll("<", "\\u003c")};\n`
);
console.log(`Imported ${Object.keys(importedClips).length} clips from ${source} into ${generatedPath}`);
